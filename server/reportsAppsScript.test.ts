import assert from 'node:assert/strict';
import test from 'node:test';
import { plain } from './fakeSpreadsheet.ts';
import { harness, session } from './octoberVerified.ts';

function line(page: { lines: { key: string; result: string; source: string; status: string }[] }, key: string) {
  const found = page.lines.find((item) => item.key === key);
  assert.ok(found, key);
  return found!;
}

test('a missing report stays Pending and a blank on a complete report is zero', () => {
  const { gs } = harness();
  assert.equal(plain(gs.reportCompleteNumber_(false, null)).pending, true);
  assert.equal(plain(gs.reportCompleteNumber_(false, '')).value, null);
  assert.equal(plain(gs.reportCompleteNumber_(true, '')).value, 0);
  assert.equal(plain(gs.reportCompleteNumber_(true, null)).value, 0);
  assert.equal(plain(gs.reportCompleteNumber_(true, 0)).value, 0);
});

test('the daily summary uses Morning Start-Up figures and does not email', () => {
  const { gs, mail, setToday } = harness();
  setToday('2026-10-18');
  const before = plain(gs.home_({ session }));
  assert.deepEqual(plain(gs.ROUTES_).reports, ['sales', 'manager', 'admin']);
  assert.throws(() => gs.reportCenter_({ session: { role: 'sales', username: 'sales17' }, kind: 'daily' }));
  const facts = plain(gs.dailyFacts_());
  const writtenThrough = facts.filter((row: { date: string; nwdsrWritten: number | null }) => row.date <= '2026-10-16' && row.date >= '2026-10-02' && row.nwdsrWritten !== null).map((row: { date: string }) => row.date).sort().pop();
  const deliveredThrough = facts.filter((row: { date: string; nwdsrDelivered: number | null }) => row.date <= '2026-10-16' && row.date >= '2026-10-02' && row.nwdsrDelivered !== null).map((row: { date: string }) => row.date).sort().pop();
  const writtenMtd = plain(gs.sumField_(facts, 'nwdsrWritten', '2026-10-02', writtenThrough));
  const deliveredMtd = plain(gs.sumField_(facts, 'nwdsrDelivered', '2026-10-02', deliveredThrough));
  const page = plain(gs.reportCenter_({ session, kind: 'daily', date: '2026-10-16' }));
  assert.equal(page.date, '2026-10-16');
  assert.equal(page.mail, false);
  assert.equal(page.ready, true);
  assert.equal(line(page, 'written-mtd').result, plain(gs.moneyText_(writtenMtd)));
  assert.equal(line(page, 'delivered-mtd').result, plain(gs.moneyText_(deliveredMtd)));
  assert.match(line(page, 'written-mtd').source, new RegExp('through ' + writtenThrough));
  assert.match(line(page, 'delivered-mtd').source, new RegExp('through ' + deliveredThrough));
  assert.equal(before.month.written, writtenMtd);
  assert.equal(before.month.delivered, deliveredMtd);
  const day = facts.find((row: { date: string }) => row.date === '2026-10-16');
  assert.equal(line(page, 'written').result, day && day.nwdsrWritten !== null ? plain(gs.moneyText_(day.nwdsrWritten)) : 'Pending');
  const monthClosing = before.closing.mtd;
  if (monthClosing.through && monthClosing.through <= '2026-10-16' && monthClosing.ratio !== null) {
    assert.equal(line(page, 'closing-mtd').result, plain(gs.percentText_(monthClosing.ratio)));
    assert.match(line(page, 'closing-mtd').source, new RegExp(monthClosing.through));
  } else {
    assert.equal(line(page, 'closing-mtd').result, 'Pending');
  }
  assert.ok(page.priorities.length <= 3);
  assert.match(page.calendarNote, /2nd through the 1st/);
  assert.match(page.calendarNote, /1st through the last calendar day/);
  assert.match(page.verification, /2026-10-16|Oct 16, 2026/);
  assert.match(page.storePeriod, /2026-10-02/);
  assert.match(page.individualPeriod, /2026-10-01/);
  const yesterday = plain(gs.reportCenter_({ session, kind: 'daily' }));
  assert.equal(yesterday.date, '2026-10-17');
  const missing = plain(gs.reportCenter_({ session, kind: 'daily', date: '2026-10-17' }));
  assert.equal(missing.date, '2026-10-17');
  assert.equal(line(missing, 'written').result, 'Pending');
  assert.equal(line(missing, 'delivered').result, 'Pending');
  assert.equal(line(missing, 'written').result === '$0', false);
  assert.match(line(missing, 'written-mtd').source, new RegExp('through ' + writtenThrough));
  assert.match(line(missing, 'written-mtd').source, /not included/);
  assert.equal(line(missing, 'written-mtd').result, plain(gs.moneyText_(writtenMtd)));
  const monthly = plain(gs.reportCenter_({ session, kind: 'monthly' }));
  assert.equal(monthly.ready, false);
  assert.equal(monthly.lines.length, 0);
  assert.equal(monthly.pdf, '');
  assert.match(monthly.notice, /not built yet/);
  const pdf = Buffer.from(page.pdf, 'base64').toString('latin1');
  assert.match(pdf, /^%PDF-1\.4/);
  assert.equal((pdf.match(/\/Type \/Page[^s]/g) || []).length, 1);
  assert.match(pdf, /MediaBox \[0 0 612 792\]/);
  assert.match(pdf, /Daily Management Summary/);
  const after = plain(gs.home_({ session }));
  assert.equal(after.month.written, before.month.written);
  assert.equal(after.month.delivered, before.month.delivered);
  assert.equal(mail.length, 0);
});

test('the weekly executive report uses a completed Monday-Sunday week and keeps missing days Pending', () => {
  const { gs, mail, setToday } = harness();
  setToday('2026-10-18');
  const before = plain(gs.home_({ session }));
  assert.equal(gs.reportWeekday_('2026-10-18'), 0);
  assert.equal(gs.reportWeekday_('2026-10-12'), 1);
  const page = plain(gs.reportCenter_({ session, kind: 'weekly' }));
  assert.equal(page.ready, true);
  assert.equal(page.partial, false);
  assert.equal(page.period.start, '2026-10-05');
  assert.equal(page.period.end, '2026-10-11');
  assert.match(page.partialLabel, /Completed week/);
  const facts = plain(gs.dailyFacts_());
  const closed = plain(gs.closedDates_());
  const expected = plain(gs.reportRangeField_(facts, 'nwdsrWritten', '2026-10-05', '2026-10-11', closed));
  const written = page.weekly.find((item: { key: string }) => item.key === 'week-written');
  assert.equal(written.result, expected.pending ? 'Pending' : plain(gs.moneyText_(expected.value)));
  assert.equal(page.weekly.find((item: { key: string }) => item.key === 'week-ticket').result, 'Pending');
  assert.equal(page.lastYear.written, 'Pending');
  assert.equal(page.lastYear.delivered, 'Pending');
  assert.match(page.verification, /Last year is Pending/);
  assert.match(page.calendarNote, /2nd through the 1st/);
  assert.match(page.calendarNote, /SNAP/);
  assert.ok(page.summary.wins.length <= 3);
  assert.ok(page.summary.attention.length <= 3);
  assert.ok(page.summary.priorities.length <= 3);
  const mtd = page.month.find((item: { key: string }) => item.key === 'mtd-written');
  assert.match(mtd.source, /Store month/);
  assert.match(mtd.caption, /Store month through/);
  assert.equal(String(mtd.caption).includes('Oct 16'), false);
  assert.equal(String(mtd.caption).includes('Oct 17'), false);
  assert.match(page.month.find((item: { key: string }) => item.key === 'mtd-written-projection').caption, /Projection through/);
  assert.match(page.weekly.find((item: { key: string }) => item.key === 'week-written').caption, /Oct 5, 2026/);
  assert.equal(mtd.source.includes('2026-10-16'), false);
  assert.equal(mtd.source.includes('2026-10-17'), false);
  const wtd = plain(gs.reportCenter_({ session, kind: 'weekly', span: 'week-to-date' }));
  assert.equal(wtd.partial, true);
  assert.equal(wtd.period.start, '2026-10-12');
  assert.equal(wtd.period.end, '2026-10-17');
  assert.equal(wtd.weekly.find((item: { key: string }) => item.key === 'week-written').result, 'Pending');
  const custom = plain(gs.reportCenter_({ session, kind: 'weekly', span: 'custom', start: '2026-10-12', end: '2026-10-16' }));
  assert.equal(custom.partial, true);
  assert.match(custom.partialLabel, /Partial/);
  const pdf = Buffer.from(page.pdf, 'base64').toString('latin1');
  assert.match(pdf, /^%PDF-1\.4/);
  assert.equal((pdf.match(/\/Type \/Page[^s]/g) || []).length, 1);
  assert.match(pdf, /Weekly Executive Report/);
  const after = plain(gs.home_({ session }));
  assert.equal(after.month.written, before.month.written);
  assert.equal(after.month.delivered, before.month.delivered);
  assert.equal(mail.length, 0);
});

test('an individual weekly report uses SNAP for volume and keeps Group 17 and PERQ labeled', () => {
  const { gs, tabs, mail, setToday } = harness();
  setToday('2026-10-18');
  const before = plain(gs.home_({ session }));
  const eric = plain(gs.reportCenter_({ session, kind: 'individual', name: 'Eric Montes Rodriguez' }));
  assert.equal(eric.ready, true);
  assert.equal(eric.partial, false);
  assert.equal(eric.period.start, '2026-10-05');
  assert.equal(eric.period.end, '2026-10-11');
  assert.equal(eric.newHire, false);
  assert.ok(!eric.associates.some((name: string) => /Kelly|Caroline|Mukhtar|James/.test(name)));
  const snap = plain(gs.reportPersonSnap_('Eric Montes Rodriguez', '2026-10-05', '2026-10-11'));
  const written = eric.performance.find((item: { key: string }) => item.key === 'snap-week');
  assert.equal(written.result, snap.pending ? 'Pending' : plain(gs.moneyText_(snap.value)));
  assert.match(written.source, /SNAP Written/);
  const orders = eric.performance.find((item: { key: string }) => item.key === 'orders');
  assert.match(orders.source, /Group 17/);
  assert.match(orders.source, /Not SNAP dollars/);
  const ticket = eric.performance.find((item: { key: string }) => item.key === 'ticket');
  assert.match(ticket.goal, /\$2,500/);
  assert.match(eric.quality.find((item: { key: string }) => item.key === 'rugs').result, /Pending/);
  assert.ok(eric.coaching.strengths.length <= 2);
  assert.ok(eric.coaching.improvements.length <= 2);
  assert.equal(typeof eric.coaching.goal, 'string');
  assert.match(eric.coaching.notes, /Nothing is saved or emailed/);
  const brenda = plain(gs.reportCenter_({ session, kind: 'individual', name: 'Brenda Sanchez' }));
  assert.equal(brenda.performance.find((item: { key: string }) => item.key === 'snap-week').result, 'Not employed');
  const current = plain(gs.reportCenter_({ session, kind: 'individual', name: 'Brenda Sanchez', span: 'week-to-date' }));
  assert.equal(current.partial, true);
  assert.equal(current.period.start, '2026-10-12');
  assert.equal(current.newHire, true);
  assert.equal(current.performance.find((item: { key: string }) => item.key === 'volume-goal').result, '$0');
  assert.match(current.verification, /NEW HIRE/);
  assert.throws(() => gs.reportCenter_({ session, kind: 'individual', name: 'Caroline Amaro' }));
  assert.throws(() => gs.reportCenter_({ session: { role: 'sales', username: 'sales17' }, kind: 'individual', name: 'Eric Montes Rodriguez' }));
  tabs.CC_Config.push(['employee_report_access', 'yes']);
  tabs.CC_Config.push(['employee_report_sales17', 'Brenda Sanchez']);
  assert.throws(() => gs.reportCenter_({ session: { role: 'sales', username: 'sales17' }, kind: 'weekly' }));
  const own = plain(gs.reportCenter_({ session: { role: 'sales', username: 'sales17' }, kind: 'individual', name: 'Eric Montes Rodriguez' }));
  assert.equal(own.name, 'Brenda Sanchez');
  assert.deepEqual(own.associates, ['Brenda Sanchez']);
  const pdf = Buffer.from(eric.pdf, 'base64').toString('latin1');
  assert.match(pdf, /^%PDF-1\.4/);
  assert.equal((pdf.match(/\/Type \/Page[^s]/g) || []).length, 1);
  assert.match(pdf, /Weekly Salesperson Report/);
  const after = plain(gs.home_({ session }));
  assert.equal(after.month.written, before.month.written);
  assert.equal(after.month.delivered, before.month.delivered);
  assert.equal(mail.length, 0);
});
